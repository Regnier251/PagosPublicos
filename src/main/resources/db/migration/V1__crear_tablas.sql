CREATE TABLE terceros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfc VARCHAR(13) NOT NULL UNIQUE,
    razon_social VARCHAR(255) NOT NULL,
    estatus VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cuentas_bancarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tercero_id BIGINT NOT NULL,
    banco VARCHAR(100) NOT NULL,
    clabe VARCHAR(18) UNIQUE,
    titular VARCHAR(255) NOT NULL,
    estatus VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT fk_cuentas_tercero FOREIGN KEY (tercero_id) REFERENCES terceros (id)
);

CREATE TABLE documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tercero_id BIGINT NOT NULL,
    tipo VARCHAR(3) NOT NULL CHECK (tipo IN ('CXC', 'CXP')),
    folio VARCHAR(50) NOT NULL,
    fecha_emision DATE,
    fecha_vencimiento DATE,
    monto_total NUMERIC(18,2) NOT NULL CHECK (monto_total > 0),
    saldo_pendiente NUMERIC(18,2) NOT NULL CHECK (saldo_pendiente >= 0),
    estatus VARCHAR(20) NOT NULL DEFAULT 'VIGENTE',
    CONSTRAINT fk_documentos_tercero FOREIGN KEY (tercero_id) REFERENCES terceros (id)
);

CREATE TABLE compensaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(30) NOT NULL UNIQUE,
    tercero_id BIGINT NOT NULL,
    cuenta_bancaria_id BIGINT,
    monto_compensado NUMERIC(18,2) NOT NULL,
    saldo_residual NUMERIC(18,2) NOT NULL DEFAULT 0,
    observaciones TEXT,
    estatus VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    CONSTRAINT fk_comp_tercero FOREIGN KEY (tercero_id) REFERENCES terceros (id),
    CONSTRAINT fk_comp_cuenta FOREIGN KEY (cuenta_bancaria_id) REFERENCES cuentas_bancarias (id)
);

CREATE TABLE detalle_compensacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compensacion_id BIGINT NOT NULL,
    documento_id BIGINT NOT NULL,
    monto_aplicado NUMERIC(18,2) NOT NULL CHECK (monto_aplicado > 0),
    CONSTRAINT fk_detalle_comp FOREIGN KEY (compensacion_id) REFERENCES compensaciones (id),
    CONSTRAINT fk_detalle_doc FOREIGN KEY (documento_id) REFERENCES documentos (id),
    CONSTRAINT uq_detalle_comp_doc UNIQUE (compensacion_id, documento_id)
);