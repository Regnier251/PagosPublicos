CREATE TABLE chat_consultas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(100) NOT NULL,
    pregunta TEXT NOT NULL,
    respuesta TEXT NOT NULL,
    herramientas_usadas VARCHAR(500),
    duracion_ms BIGINT NOT NULL,
    consultado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_chat_consultas_usuario ON chat_consultas (nombre_usuario);
CREATE INDEX idx_chat_consultas_fecha ON chat_consultas (consultado_en);