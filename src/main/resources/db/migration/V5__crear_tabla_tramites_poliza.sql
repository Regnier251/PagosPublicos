CREATE TABLE tramites_poliza (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_proveedor_sap VARCHAR(255) NOT NULL,
    persona_tramite VARCHAR(255) NOT NULL,
    referencia VARCHAR(50) NOT NULL,
    fecha_compensacion DATE NOT NULL,
    fecha_carpeta DATE NOT NULL,
    sufijo_corte VARCHAR(1) NOT NULL DEFAULT '',
    ruta_relativa VARCHAR(1000) NOT NULL,
    suma_verificacion VARCHAR(64) NOT NULL UNIQUE,
    estatus VARCHAR(20) NOT NULL DEFAULT 'RECIBIDO',
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_tramites_fecha_carpeta ON tramites_poliza (fecha_carpeta);